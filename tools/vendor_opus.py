#!/usr/bin/env python3
"""
Vendor the libopus decoder into src/opus/ so the Arduino IDE can build it
without extra compiler flags (Arduino compiles src/ recursively but cannot add
-I paths per sketch).

Usage:  python3 -I tools/vendor_opus.py <extracted opus-1.5.2 dir> <sketch dir>

What it does:
  * copies the sources listed in celt_sources.mk (CELT_SOURCES),
    silk_sources.mk (SILK_SOURCES, SILK_SOURCES_FIXED) and the decoder part of
    opus_sources.mk, plus all top-level headers of include/ celt/ silk/
    silk/fixed/ src/; no CPU-specific subfolders, no float SILK, no DNN
  * rewrites #include "x.h" to a path relative to the including file, using
    the same search order as upstream's Makefile.am (-Iinclude -Icelt -Isilk
    -Isilk/fixed); includes it cannot resolve (arch-specific, inside #if
    blocks that are off here) are left alone
  * replaces "#ifdef HAVE_CONFIG_H" with "#if 1" so every file picks up the
    vendored config.h (fixed point, decoder only, C99 VLAs)
"""
import os, re, shutil, sys

src_root, sketch = sys.argv[1], sys.argv[2]
dst_root = os.path.join(sketch, 'src', 'opus')

def mk_vars(name):
    text = open(os.path.join(src_root, name)).read().replace('\\\n', ' ')
    out = {}
    for m in re.finditer(r'^([A-Z_0-9]+)\s*=\s*(.*)$', text, re.M):
        out[m.group(1)] = m.group(2).split()
    return out

celt, silk, opus = mk_vars('celt_sources.mk'), mk_vars('silk_sources.mk'), mk_vars('opus_sources.mk')
decoder_top = {'src/opus.c', 'src/opus_decoder.c', 'src/extensions.c'}
sources = (celt['CELT_SOURCES'] + silk['SILK_SOURCES'] + silk['SILK_SOURCES_FIXED']
           + [s for s in opus['OPUS_SOURCES'] if s in decoder_top])
missing = decoder_top - set(opus['OPUS_SOURCES'])
assert not missing, missing

header_dirs = ['include', 'celt', 'silk', 'silk/fixed', 'src']
files = list(sources)
for d in header_dirs:
    for f in sorted(os.listdir(os.path.join(src_root, d))):
        if f.endswith('.h'):
            files.append(f'{d}/{f}')

if os.path.isdir(dst_root):
    shutil.rmtree(dst_root)
for f in files:
    os.makedirs(os.path.dirname(os.path.join(dst_root, f)), exist_ok=True)
    shutil.copy2(os.path.join(src_root, f), os.path.join(dst_root, f))
shutil.copy2(os.path.join(src_root, 'COPYING'), os.path.join(dst_root, 'COPYING'))

open(os.path.join(dst_root, 'config.h'), 'w').write('''\
/* libopus build configuration for the ESP32-P4 Arduino sketch (decoder only). */
#ifndef OPUS_VENDORED_CONFIG_H
#define OPUS_VENDORED_CONFIG_H
#define OPUS_BUILD 1
#define FIXED_POINT 1          /* integer decoder: fast and well tested on MCUs */
#define DISABLE_FLOAT_API 1    /* we only call opus_decode() (int16 output) */
#define VAR_ARRAYS 1           /* scratch on the stack: give the decoding task ~32 KB */
#define HAVE_LRINT 1
#define HAVE_LRINTF 1
#define PACKAGE_VERSION "1.5.2"
#endif
''')

search = header_dirs[:-1] + ['']          # upstream -I order, then config.h at the root
inc_re = re.compile(r'^(\s*#\s*include\s*)"([^"]+)"', re.M)
unresolved, rewritten = set(), 0
for f in files + ['config.h']:
    p = os.path.join(dst_root, f)
    if not p.endswith(('.c', '.h')):
        continue
    here = os.path.dirname(p)
    s = open(p, encoding='latin-1').read()
    def fix(m):
        global rewritten
        name = m.group(2)
        if os.path.exists(os.path.join(here, name)):
            return m.group(0)
        for d in search:
            cand = os.path.join(dst_root, d, name)
            if os.path.exists(cand):
                rewritten += 1
                return f'{m.group(1)}"{os.path.relpath(cand, here)}"'
        unresolved.add(name)
        return m.group(0)
    s = inc_re.sub(fix, s)
    s = re.sub(r'^#\s*ifdef\s+HAVE_CONFIG_H\b', '#if 1 /* HAVE_CONFIG_H (vendored) */', s, flags=re.M)
    open(p, 'w', encoding='latin-1').write(s)

open(os.path.join(dst_root, 'VENDORED.md'), 'w').write(f'''\
# libopus 1.5.2 (decoder), vendored

Source: https://downloads.xiph.org/releases/opus/opus-1.5.2.tar.gz
SHA-256: 65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1
Licence: BSD-3-Clause (see COPYING)

Generated by `tools/vendor_opus.py` - do not edit by hand; re-run the script.
Changes from upstream: only `#include "..."` paths (made relative) and
`#ifdef HAVE_CONFIG_H` -> `#if 1`, plus the `config.h` here.

Files: {len(sources)} sources, {len(files) - len(sources)} headers.
Unresolved includes (arch-specific, disabled in this config): {", ".join(sorted(unresolved)) or "none"}
''')
print(f'{len(sources)} sources, {len(files)-len(sources)} headers, {rewritten} includes rewritten')
print('unresolved (left as is):', sorted(unresolved))
